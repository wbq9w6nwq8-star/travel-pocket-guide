def _tz_has_dst(tz_name: str, fallback: bool) -> bool:
    """tzdata から夏時間の有無を判定（手入力の has_dst は制度変更に追随できないため）。
    例: 2026年にカナダ西部（BC州・アルバータ州）が夏時間を廃止している。"""
    try:
        from datetime import datetime, timezone
        from zoneinfo import ZoneInfo
        z = ZoneInfo(tz_name)
        jan = datetime(2027, 1, 15, 12, tzinfo=timezone.utc).astimezone(z).utcoffset()
        jul = datetime(2027, 7, 15, 12, tzinfo=timezone.utc).astimezone(z).utcoffset()
        return jan != jul
    except Exception:
        return fallback


